def detect_reuse(ciphertexts):
    groups = {}
    for i, (gb, y) in enumerate(ciphertexts):
        if gb not in groups:
            groups[gb] = []
        groups[gb].append(i)
    return {gb: indices for gb, indices in groups.items() if len(indices) > 1}

def recover_with_known_plain(group_indices, known_index, ciphertexts, x_known, p):
    y_known = ciphertexts[known_index][1]
    mask = (y_known * pow(x_known, -1, p)) % p
    mask_inv = pow(mask, -1, p)
    recovered = {}
    for i in group_indices:
        y = ciphertexts[i][1]
        recovered[i] = (y * mask_inv) % p
    return recovered

